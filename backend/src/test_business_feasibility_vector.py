def print_results(result, test_name: str):
    """打印测试结果"""
    print(f"\n【{test_name}】")
    print(f"✓ 成功: {result.success}")
    print(f"✓ 总匹配数: {result.total_matches}")
    print(f"✓ 平均置信度: {result.avg_confidence:.3f}")
    print(f"✓ 执行时间: {result.execution_time:.3f}秒")

    if result.total_matches > 0:
        print(f"\n各维度匹配详情:")
        for dim_id, matches in result.dimensions.items():
            print(f"\n  [{matches[0].dimension_name}] - {len(matches)}个匹配")
            for i, match in enumerate(matches[:3], 1):  # 只显示前3个
                print(f"    {i}. 相似度 {match.similarity:.3f}: {match.sentence[:60]}...")


